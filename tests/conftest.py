from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from edit_videos_poc import config
from edit_videos_poc.pipeline._ffmpeg import ffmpeg_exe, run_ffmpeg


@pytest.fixture(autouse=True)
def isolated_dirs(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Point every output/data path at a throwaway directory."""
    monkeypatch.setattr(config, "WORK_DIR", tmp_path / "work")
    monkeypatch.setattr(config, "DATA_DIR", tmp_path / "data")
    return tmp_path


@pytest.fixture(scope="session")
def sample_video(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """A 3-second 320x240 test pattern with a tone, generated by ffmpeg."""
    out = tmp_path_factory.mktemp("media") / "sample.mp4"
    run_ffmpeg([
        "ffmpeg", "-y",
        "-f", "lavfi", "-i", "testsrc=d=3:s=320x240:r=10",
        "-f", "lavfi", "-i", "sine=f=440:d=3",
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-g", "10", "-c:a", "aac", "-shortest",
        str(out),
    ])
    return out


def media_duration(path: Path) -> float:
    """Container duration in seconds, read from ffmpeg's own banner (no ffprobe dependency)."""
    proc = subprocess.run([ffmpeg_exe(), "-hide_banner", "-i", str(path)], capture_output=True, text=True, encoding="utf-8", errors="replace")
    stamp = proc.stderr.split("Duration:")[1].split(",")[0].strip()
    hours, minutes, seconds = stamp.split(":")
    return int(hours) * 3600 + int(minutes) * 60 + float(seconds)
